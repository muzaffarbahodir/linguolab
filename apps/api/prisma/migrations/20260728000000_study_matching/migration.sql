-- Подбор курса по предпочтениям студента.
--
-- Опрос при первом входе собирал формат, направление и режим — и ничего из
-- этого нигде не читалось. Чтобы выдача действительно зависела от ответов,
-- нужны две вещи: явный формат у курса и то, чего опрос не спрашивал вовсе —
-- цель, уровень и удобное время.

-- ── Курс: формат отдельным полем ─────────────────────────────────────────────
-- Раньше формат угадывали по room_id, но null там значит и «онлайн», и
-- «аудиторию ещё не назначили». Ранжировать выдачу по такому признаку нельзя.
ALTER TABLE "Class" ADD COLUMN "format" "StudyFormat" NOT NULL DEFAULT 'OFFLINE';

-- Бэкфилл: ссылка на встречу есть, аудитории нет — курс вели онлайн.
-- Обратное неверно, поэтому остальные остаются очными: ошибиться в сторону
-- «очно» безопаснее, очный курс студент просто не увидит первым в списке.
UPDATE "Class"
   SET "format" = 'ONLINE'
 WHERE "room_id" IS NULL
   AND "meeting_url" IS NOT NULL
   AND "meeting_url" <> '';

-- ── Студент: цель, уровень и удобное время ───────────────────────────────────
ALTER TABLE "User"
  ADD COLUMN "learning_goal"   TEXT,
  ADD COLUMN "self_level"      "CEFR",
  ADD COLUMN "available_days"  TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN "available_slots" TEXT[] NOT NULL DEFAULT '{}';

-- Выдача рекомендаций фильтрует активные курсы по формату и уровню.
CREATE INDEX "Class_format_level_idx" ON "Class"("format", "level");
